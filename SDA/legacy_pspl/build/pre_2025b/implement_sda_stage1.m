function implement_sda_stage1()
%IMPLEMENT_SDA_STAGE1 Implement PL problem latch and SDA initialization.

rootDir = fileparts(mfilename('fullpath'));
modelFile = fullfile(rootDir, 'FCSMPC_double_vector.slx');
model = 'FCSMPC_double_vector';
base = [model '/FCS_MPC/SDA_Solve/SDA Solve/SDA/' ...
    'double_vector_matlab_FSM_Calc/SDA_Solve/PL_Framework'];

backupDir = fullfile(rootDir, 'backups');
if ~isfolder(backupDir), mkdir(backupDir); end
stamp = datestr(now, 'yyyymmdd_HHMMSS');
copyfile(modelFile, fullfile(backupDir, ...
    ['FCSMPC_double_vector_before_stage1_' stamp '.slx']));

load_system(modelFile);
cleanup = onCleanup(@() close_system(model, 0));
sf = sfroot;

set_script(sf, [base '/ProblemLatch'], problem_latch_code());
set_script(sf, [base '/SdaInitializer'], initializer_code());
set_script(sf, [base '/BestMemory'], best_memory_code());
set_script(sf, [base '/BranchMemory'], branch_memory_code());

configure_data(sf, [base '/ProblemLatch'], 'problemIn', ...
    'Bus: SdaProblemBus', '[1 1]');
configure_data(sf, [base '/ProblemLatch'], 'problem', ...
    'Bus: SdaProblemBus', '[1 1]');
configure_data(sf, [base '/ProblemLatch'], 'loadEnable', ...
    'boolean', '[1 1]');

configure_data(sf, [base '/SdaInitializer'], 'problem', ...
    'Bus: SdaProblemBus', '[1 1]');
configure_data(sf, [base '/SdaInitializer'], 'start', ...
    'boolean', '[1 1]');
configure_data(sf, [base '/SdaInitializer'], 'done', ...
    'boolean', '[1 1]');
configure_data(sf, [base '/SdaInitializer'], 'valid', ...
    'boolean', '[1 1]');
configure_data(sf, [base '/SdaInitializer'], 'z', ...
    'double', '[15 1]');
configure_data(sf, [base '/SdaInitializer'], 'initialU', ...
    'double', '[15 1]');
configure_data(sf, [base '/SdaInitializer'], 'initialMetric', ...
    'double', '[1 1]');
configure_data(sf, [base '/SdaInitializer'], 'initialCMVCost', ...
    'double', '[1 1]');
configure_data(sf, [base '/SdaInitializer'], 'Jround', ...
    'double', '[1 1]');
configure_data(sf, [base '/SdaInitializer'], 'Jshift', ...
    'double', '[1 1]');

configure_data(sf, [base '/BestMemory'], 'writeEnable', ...
    'boolean', '[1 1]');
configure_data(sf, [base '/BestMemory'], 'initialU', ...
    'double', '[15 1]');
configure_data(sf, [base '/BestMemory'], 'metric', ...
    'double', '[1 1]');
configure_data(sf, [base '/BestMemory'], 'cmvCost', ...
    'double', '[1 1]');
configure_data(sf, [base '/BestMemory'], 'best', ...
    'Bus: SdaBestBus', '[1 1]');

configure_data(sf, [base '/BranchMemory'], 'clear', ...
    'boolean', '[1 1]');
configure_data(sf, [base '/BranchMemory'], 'writeEnable', ...
    'boolean', '[1 1]');
configure_data(sf, [base '/BranchMemory'], 'metric', ...
    'double', '[1 1]');
configure_data(sf, [base '/BranchMemory'], 'vectorMetric', ...
    'double', '[1 1]');
configure_data(sf, [base '/BranchMemory'], 'z', ...
    'double', '[15 1]');
configure_data(sf, [base '/BranchMemory'], 'iabcInitial', ...
    'double', '[3 1]');
configure_data(sf, [base '/BranchMemory'], 'memory', ...
    'Bus: SdaMemoryBus', '[1 1]');

% Rewire BestMemory to the initializer result. Search-result update is a
% later stage and is deliberately disconnected for now.
rewire_input(base, 'BestMemory', 1, 'SdaInitializer', 1);
rewire_input(base, 'BestMemory', 3, 'SdaInitializer', 5);
connect_if_free(base, 'SdaInitializer', 6, 'BestMemory', 4);

% Initializer completion writes z and initial current into BranchMemory.
% Keep the later FSM memWrite path through an OR gate.
orPath = [base '/BranchWriteOr'];
if getSimulinkBlockHandle(orPath) <= 0
    add_block('simulink/Logic and Bit Operations/Logical Operator', ...
        orPath, 'Operator', 'OR', 'Inputs', '2', ...
        'Position', [735 420 770 455]);
end
branchPorts = get_param([base '/BranchMemory'], 'PortHandles');
oldLine = get_param(branchPorts.Inport(2), 'Line');
if oldLine ~= -1
    oldSource = get_param(oldLine, 'SrcPortHandle');
    delete_line(oldLine);
else
    oldSource = [];
end
orPorts = get_param(orPath, 'PortHandles');
if ~isempty(oldSource)
    add_line(base, oldSource, orPorts.Inport(1), 'autorouting', 'on');
end
initializerPorts = get_param([base '/SdaInitializer'], 'PortHandles');
add_line(base, initializerPorts.Outport(1), orPorts.Inport(2), ...
    'autorouting', 'on');
add_line(base, orPorts.Outport(1), branchPorts.Inport(2), ...
    'autorouting', 'on');

connect_if_free(base, 'iabcCompensated', 1, 'BranchMemory', 6);

% Document the intentionally unconnected first-stage diagnostics.
add_terminator(base, 'InitJroundTerminator', 'SdaInitializer', 7, ...
    [720 560 740 580]);
add_terminator(base, 'InitJshiftTerminator', 'SdaInitializer', 8, ...
    [750 560 770 580]);

set_param(model, 'SimulationCommand', 'update');
save_system(model, modelFile);
fprintf('SDA stage 1 implemented and model updated successfully.\n');
end

function set_script(sf, path, code)
chart = sf.find('-isa', 'Stateflow.EMChart', 'Path', path);
if isempty(chart), error('Missing MATLAB Function: %s', path); end
chart.Script = code;
end

function configure_data(sf, path, name, type, sizeText)
chart = sf.find('-isa', 'Stateflow.EMChart', 'Path', path);
data = chart.find('-isa', 'Stateflow.Data', 'Name', name);
if isempty(data), error('Missing data %s in %s', name, path); end
data.DataType = type;
data.Props.Array.Size = sizeText;
end

function rewire_input(parent, dstName, dstPort, srcName, srcPort)
dst = get_param([parent '/' dstName], 'PortHandles');
line = get_param(dst.Inport(dstPort), 'Line');
if line ~= -1, delete_line(line); end
src = get_param([parent '/' srcName], 'PortHandles');
add_line(parent, src.Outport(srcPort), dst.Inport(dstPort), ...
    'autorouting', 'on');
end

function connect_if_free(parent, srcName, srcPort, dstName, dstPort)
src = get_param([parent '/' srcName], 'PortHandles');
dst = get_param([parent '/' dstName], 'PortHandles');
line = get_param(dst.Inport(dstPort), 'Line');
if line == -1
    add_line(parent, src.Outport(srcPort), dst.Inport(dstPort), ...
        'autorouting', 'on');
end
end

function add_terminator(parent, name, srcName, srcPort, position)
path = [parent '/' name];
if getSimulinkBlockHandle(path) > 0, return; end
add_block('simulink/Sinks/Terminator', path, 'Position', position);
src = get_param([parent '/' srcName], 'PortHandles');
dst = get_param(path, 'PortHandles');
line = get_param(src.Outport(srcPort), 'Line');
if line == -1
    add_line(parent, src.Outport(srcPort), dst.Inport(1), ...
        'autorouting', 'on');
end
end

function code = problem_latch_code()
code = sprintf([ ...
    'function problem = ProblemLatch(problemIn, loadEnable)\n' ...
    '%%#codegen\n' ...
    'persistent latchedProblem\n' ...
    'if isempty(latchedProblem)\n' ...
    '    latchedProblem = problemIn;\n' ...
    'end\n' ...
    'if loadEnable\n' ...
    '    latchedProblem = problemIn;\n' ...
    'end\n' ...
    'problem = latchedProblem;\n']);
end

function code = initializer_code()
code = sprintf([ ...
    'function [done, valid, z, initialU, initialMetric, initialCMVCost, Jround, Jshift] = SdaInitializer(problem, start)\n' ...
    '%%#codegen\n' ...
    'persistent zReg uReg metricReg cmvReg jRoundReg jShiftReg validReg\n' ...
    'if isempty(zReg)\n' ...
    '    zReg=zeros(15,1); uReg=zeros(15,1); metricReg=realmax;\n' ...
    '    cmvReg=0.0; jRoundReg=0.0; jShiftReg=0.0; validReg=false;\n' ...
    'end\n' ...
    'done=false;\n' ...
    'if start\n' ...
    '    zReg=problem.H*problem.U_unc;\n' ...
    '    uRound=zeros(15,1); uShift=zeros(15,1);\n' ...
    '    for k=1:15\n' ...
    '        uRound(k)=min(max(round(problem.U_unc(k)),0.0),1.0);\n' ...
    '    end\n' ...
    '    for k=1:12\n' ...
    '        uShift(k)=problem.UoptPrev(k+3);\n' ...
    '    end\n' ...
    '    for k=13:15\n' ...
    '        uShift(k)=problem.UoptPrev(k);\n' ...
    '    end\n' ...
    '    jRoundReg=quadratic_cost(problem.H,uRound,problem.U_unc);\n' ...
    '    jShiftReg=quadratic_cost(problem.H,uShift,problem.U_unc);\n' ...
    '    if jShiftReg < jRoundReg\n' ...
    '        uReg=uShift;\n' ...
    '    else\n' ...
    '        uReg=uRound;\n' ...
    '    end\n' ...
    '    sPrevious=problem.UoptPrev(4:6);\n' ...
    '    cmvReg=sequence_cmv_cost(uReg,sPrevious,problem);\n' ...
    '    metricReg=quadratic_cost(problem.H,uReg,problem.U_unc)+cmvReg;\n' ...
    '    validReg=isfinite(metricReg);\n' ...
    '    done=true;\n' ...
    'end\n' ...
    'valid=validReg; z=zReg; initialU=uReg; initialMetric=metricReg;\n' ...
    'initialCMVCost=cmvReg; Jround=jRoundReg; Jshift=jShiftReg;\n' ...
    'end\n\n' ...
    'function value=quadratic_cost(H,U,Uunc)\n' ...
    'residual=zeros(15,1);\n' ...
    'for row=1:15\n' ...
    '    acc=0.0;\n' ...
    '    for col=1:15\n' ...
    '        acc=acc+H(row,col)*(U(col)-Uunc(col));\n' ...
    '    end\n' ...
    '    residual(row)=acc;\n' ...
    'end\n' ...
    'value=0.0;\n' ...
    'for k=1:15\n' ...
    '    value=value+residual(k)*residual(k);\n' ...
    'end\n' ...
    'end\n\n' ...
    'function total=sequence_cmv_cost(U,sPrevious,problem)\n' ...
    'total=0.0; iabc=problem.iabcCompensated;\n' ...
    'for step=1:5\n' ...
    '    first=(step-1)*3+1; sCurrent=U(first:first+2);\n' ...
    '    [deltaStep,deltaDead]=deadtime_step(sPrevious,sCurrent,iabc,problem);\n' ...
    '    total=total+cmv_penalty(sPrevious,sCurrent,iabc,deltaDead,problem);\n' ...
    '    iabc=iabc+deltaStep; sPrevious=sCurrent;\n' ...
    'end\n' ...
    'end\n\n' ...
    'function [deltaStep,deltaDead]=deadtime_step(sPrevious,sCurrent,iabc,problem)\n' ...
    'sDead=sCurrent; signEps=0.1*problem.currentEpsMargin;\n' ...
    'for phase=1:3\n' ...
    '    if sPrevious(phase)~=sCurrent(phase)\n' ...
    '        if iabc(phase)>=signEps\n' ...
    '            sDead(phase)=0.0;\n' ...
    '        elseif iabc(phase)<=-signEps\n' ...
    '            sDead(phase)=1.0;\n' ...
    '        elseif signEps>0.0\n' ...
    '            sDead(phase)=0.5*(1.0-iabc(phase)/signEps);\n' ...
    '        else\n' ...
    '            sDead(phase)=0.5;\n' ...
    '        end\n' ...
    '    end\n' ...
    'end\n' ...
    'sEffective=problem.deadtimeRatio*sDead+(1.0-problem.deadtimeRatio)*sCurrent;\n' ...
    'deltaDead=problem.deadtimeRatio*(problem.deltaIabcBase+problem.deltaIabcSwitch*sDead);\n' ...
    'deltaStep=problem.deltaIabcBase+problem.deltaIabcSwitch*sEffective;\n' ...
    'end\n\n' ...
    'function penalty=cmv_penalty(sPrevious,sCurrent,iabc,deltaDead,problem)\n' ...
    'penalty=0.0; iabcEnd=iabc+deltaDead;\n' ...
    'lower=min(iabc,iabcEnd)-problem.currentEpsMargin;\n' ...
    'upper=max(iabc,iabcEnd)+problem.currentEpsMargin;\n' ...
    'uncertain=(lower<=0.0)&(upper>=0.0);\n' ...
    'if all(sCurrent==0.0)||all(sCurrent==1.0)\n' ...
    '    penalty=penalty+problem.lambdaZero;\n' ...
    'end\n' ...
    'changed=(sPrevious~=sCurrent);\n' ...
    'if sum(changed)~=2\n' ...
    '    return;\n' ...
    'end\n' ...
    'canZero=false(3,1); canOne=false(3,1);\n' ...
    'for phase=1:3\n' ...
    '    if ~changed(phase)\n' ...
    '        canZero(phase)=sPrevious(phase)==0.0;\n' ...
    '        canOne(phase)=sPrevious(phase)==1.0;\n' ...
    '    elseif uncertain(phase)\n' ...
    '        canZero(phase)=true; canOne(phase)=true;\n' ...
    '    elseif iabcEnd(phase)>0.0\n' ...
    '        canZero(phase)=true;\n' ...
    '    else\n' ...
    '        canOne(phase)=true;\n' ...
    '    end\n' ...
    'end\n' ...
    'if all(canZero)||all(canOne)\n' ...
    '    penalty=penalty+problem.lambdaDeadtime;\n' ...
    'end\n' ...
    'end\n']);
end

function code = best_memory_code()
code = sprintf([ ...
    'function best = BestMemory(writeEnable, initialU, metric, cmvCost)\n' ...
    '%%#codegen\n' ...
    'persistent state\n' ...
    'if isempty(state)\n' ...
    '    state.bestU=false(15,1); state.bestMetric=realmax;\n' ...
    '    state.bestCMVCost=0.0; state.bestValid=false;\n' ...
    'end\n' ...
    'if writeEnable\n' ...
    '    state.bestU=initialU>0.5; state.bestMetric=metric;\n' ...
    '    state.bestCMVCost=cmvCost; state.bestValid=isfinite(metric);\n' ...
    'end\n' ...
    'best=state;\n']);
end

function code = branch_memory_code()
code = sprintf([ ...
    'function memory = BranchMemory(clear, writeEnable, metric, vectorMetric, z, iabcInitial)\n' ...
    '%%#codegen\n' ...
    'persistent state\n' ...
    'if isempty(state)\n' ...
    '    state.Uwork=false(15,1);\n' ...
    '    state.candidatePosition=ones(15,1,''uint8'');\n' ...
    '    state.metricStack=zeros(16,1); state.cmvMetricStack=zeros(16,1);\n' ...
    '    state.iabcPrediction=zeros(3,6); state.z=zeros(15,1);\n' ...
    'end\n' ...
    'if clear\n' ...
    '    state.Uwork(:)=false; state.candidatePosition(:)=uint8(1);\n' ...
    '    state.metricStack(:)=0.0; state.cmvMetricStack(:)=0.0;\n' ...
    '    state.iabcPrediction(:)=0.0; state.z(:)=0.0;\n' ...
    'elseif writeEnable\n' ...
    '    state.z=z; state.iabcPrediction(:,1)=iabcInitial;\n' ...
    '    state.metricStack(1)=metric; state.cmvMetricStack(1)=vectorMetric;\n' ...
    'end\n' ...
    'memory=state;\n']);
end
