function implement_sda_stage3()
%IMPLEMENT_SDA_STAGE3 Add vector/dead-time/CMV calculation and memory writes.

rootDir = fileparts(mfilename('fullpath'));
modelFile = fullfile(rootDir, 'FCSMPC_double_vector.slx');
model = 'FCSMPC_double_vector';
base = [model '/FCS_MPC/SDA_Solve/SDA Solve/SDA/' ...
    'double_vector_matlab_FSM_Calc/SDA_Solve/PL_Framework'];

backupDir = fullfile(rootDir, 'backups');
if ~isfolder(backupDir), mkdir(backupDir); end
stamp = datestr(now, 'yyyymmdd_HHMMSS');
copyfile(modelFile, fullfile(backupDir, ...
    ['FCSMPC_double_vector_before_stage3_' stamp '.slx']));

load_system(modelFile);
cleanup = onCleanup(@() close_system(model, 0));
sf = sfroot;

vectorPath = [base '/VectorCostCalc'];
branchPath = [base '/BranchMemory'];
vector = sf.find('-isa', 'Stateflow.EMChart', 'Path', vectorPath);
branch = sf.find('-isa', 'Stateflow.EMChart', 'Path', branchPath);
vector.Script = vector_code();
branch.Script = branch_memory_code();

set_data(vector, 'problem', 'Bus: SdaProblemBus', '[1 1]');
set_data(vector, 'start', 'boolean', '[1 1]');
set_data(vector, 'level', 'uint8', '[1 1]');
set_data(vector, 'memory', 'Bus: SdaMemoryBus', '[1 1]');
vectorOutputs = { ...
    'done','boolean','[1 1]'; 'valid','boolean','[1 1]'; ...
    'totalMetricNew','double','[1 1]'; ...
    'cmvMetricNew','double','[1 1]'; ...
    'cmvIncrement','double','[1 1]'; ...
    'iabcNext','double','[3 1]'; ...
    'deltaStep','double','[3 1]'; ...
    'deltaDead','double','[3 1]'; ...
    'lowerBound','double','[3 1]'; ...
    'upperBound','double','[3 1]'; ...
    'deadtimeMiss','boolean','[1 1]'};
for k = 1:size(vectorOutputs,1)
    set_data(vector, vectorOutputs{k,1}, vectorOutputs{k,2}, ...
        vectorOutputs{k,3});
end

branchInputs = { ...
    'clear','boolean','[1 1]'; ...
    'initWrite','boolean','[1 1]'; ...
    'pathWrite','boolean','[1 1]'; ...
    'vectorWrite','boolean','[1 1]'; ...
    'level','uint8','[1 1]'; ...
    'fsmState','uint8','[1 1]'; ...
    'candidate','boolean','[1 1]'; ...
    'quadraticMetric','double','[1 1]'; ...
    'vectorMetric','double','[1 1]'; ...
    'cmvMetric','double','[1 1]'; ...
    'iabcNext','double','[3 1]'; ...
    'z','double','[15 1]'; ...
    'iabcInitial','double','[3 1]'};
for k = 1:size(branchInputs,1)
    set_data(branch, branchInputs{k,1}, branchInputs{k,2}, ...
        branchInputs{k,3});
end
set_data(branch, 'memory', 'Bus: SdaMemoryBus', '[1 1]');
set_data(branch, 'candidateExhausted', 'boolean', '[1 1]');

% VectorCostCalc no longer needs a separate candidate input.
disconnect_all_inputs(vectorPath);
connect(base, 'ProblemLatch', 1, 'VectorCostCalc', 1);
connect(base, 'SearchFSM', 4, 'VectorCostCalc', 2);
connect(base, 'SearchFSM', 12, 'VectorCostCalc', 3);
connect(base, 'BranchMemoryStateDelay', 1, 'VectorCostCalc', 4);

% Rebuild memory input ordering with separate path and vector write enables.
disconnect_all_inputs(branchPath);
connect(base, 'SearchFSM', 5, 'BranchMemory', 1);       % clear
connect(base, 'SdaInitializer', 1, 'BranchMemory', 2);  % initWrite
connect(base, 'SearchFSM', 6, 'BranchMemory', 3);       % pathWrite
connect(base, 'VectorCostCalc', 1, 'BranchMemory', 4);  % vectorWrite
connect(base, 'SearchFSM', 12, 'BranchMemory', 5);      % level
connect(base, 'SearchFSM', 14, 'BranchMemory', 6);      % fsmState
connect(base, 'QuadraticCalc', 7, 'BranchMemory', 7);   % candidate
connect(base, 'QuadraticCalc', 3, 'BranchMemory', 8);   % quadratic metric
connect(base, 'VectorCostCalc', 3, 'BranchMemory', 9);  % total metric
connect(base, 'VectorCostCalc', 4, 'BranchMemory', 10); % CMV metric
connect(base, 'VectorCostCalc', 6, 'BranchMemory', 11); % predicted current
connect(base, 'SdaInitializer', 3, 'BranchMemory', 12); % z
connect(base, 'iabcCompensated', 1, 'BranchMemory', 13);

% Additional calculation outputs remain observable and explicitly ended.
add_terminator(base, 'CmvIncrementTerminator', ...
    'VectorCostCalc', 5, [675 430 695 450]);
add_terminator(base, 'DeltaStepTerminator', ...
    'VectorCostCalc', 7, [675 460 695 480]);
add_terminator(base, 'DeltaDeadTerminator', ...
    'VectorCostCalc', 8, [675 490 695 510]);
add_terminator(base, 'LowerBoundTerminator', ...
    'VectorCostCalc', 9, [705 430 725 450]);
add_terminator(base, 'UpperBoundTerminator', ...
    'VectorCostCalc', 10, [705 460 725 480]);
add_terminator(base, 'DeadtimeMissTerminator', ...
    'VectorCostCalc', 11, [705 490 725 510]);

set_param(model, 'SimulationCommand', 'update');
save_system(model, modelFile);
fprintf('SDA stage 3 implemented and model updated successfully.\n');
end

function set_data(chart, name, type, sizeText)
data = chart.find('-isa', 'Stateflow.Data', 'Name', name);
if isempty(data), error('Missing data %s in %s', name, chart.Path); end
data.DataType = type;
data.Props.Array.Size = sizeText;
end

function disconnect_all_inputs(path)
ports = get_param(path, 'PortHandles');
for k = 1:numel(ports.Inport)
    line = get_param(ports.Inport(k), 'Line');
    if line ~= -1, delete_line(line); end
end
end

function connect(parent, srcName, srcPort, dstName, dstPort)
src = get_param([parent '/' srcName], 'PortHandles');
dst = get_param([parent '/' dstName], 'PortHandles');
add_line(parent, src.Outport(srcPort), dst.Inport(dstPort), ...
    'autorouting', 'on');
end

function add_terminator(parent, name, srcName, srcPort, position)
path = [parent '/' name];
src = get_param([parent '/' srcName], 'PortHandles');
if get_param(src.Outport(srcPort), 'Line') ~= -1, return; end
if getSimulinkBlockHandle(path) <= 0
    add_block('simulink/Sinks/Terminator', path, 'Position', position);
end
dst = get_param(path, 'PortHandles');
add_line(parent, src.Outport(srcPort), dst.Inport(1), ...
    'autorouting', 'on');
end

function code = vector_code()
code = sprintf([ ...
    'function [done,valid,totalMetricNew,cmvMetricNew,cmvIncrement,iabcNext,deltaStep,deltaDead,lowerBound,upperBound,deadtimeMiss] = VectorCostCalc(problem,start,level,memory)\n' ...
    '%%#codegen\n' ...
    'persistent totalReg cmvTotalReg incrementReg iabcReg stepReg deadReg lowerReg upperReg missReg validReg\n' ...
    'if isempty(totalReg)\n' ...
    '    totalReg=0.0; cmvTotalReg=0.0; incrementReg=0.0;\n' ...
    '    iabcReg=zeros(3,1); stepReg=zeros(3,1); deadReg=zeros(3,1);\n' ...
    '    lowerReg=zeros(3,1); upperReg=zeros(3,1);\n' ...
    '    missReg=false; validReg=false;\n' ...
    'end\n' ...
    'done=false;\n' ...
    'if start\n' ...
    '    idx=max(uint8(3),min(uint8(15),level));\n' ...
    '    predictionStep=idivide(idx,uint8(3));\n' ...
    '    blockEnd=double(idx); blockStart=blockEnd-2;\n' ...
    '    sCurrent=zeros(3,1); sPrevious=zeros(3,1);\n' ...
    '    for phase=1:3\n' ...
    '        sCurrent(phase)=double(memory.Uwork(blockStart+phase-1));\n' ...
    '    end\n' ...
    '    if predictionStep==uint8(1)\n' ...
    '        sPrevious=problem.UoptPrev(4:6);\n' ...
    '    else\n' ...
    '        previousStart=blockStart-3;\n' ...
    '        for phase=1:3\n' ...
    '            sPrevious(phase)=double(memory.Uwork(previousStart+phase-1));\n' ...
    '        end\n' ...
    '    end\n' ...
    '    iabcBefore=memory.iabcPrediction(:,double(predictionStep));\n' ...
    '    [stepReg,deadReg]=deadtime_step(sPrevious,sCurrent,iabcBefore,problem);\n' ...
    '    [incrementReg,lowerReg,upperReg,missReg]=cmv_penalty(sPrevious,sCurrent,iabcBefore,deadReg,problem);\n' ...
    '    totalReg=memory.metricStack(double(idx)+1)+incrementReg;\n' ...
    '    cmvTotalReg=memory.cmvMetricStack(double(idx))+incrementReg;\n' ...
    '    iabcReg=iabcBefore+stepReg;\n' ...
    '    validReg=all(isfinite(iabcReg))&&isfinite(totalReg)&&isfinite(cmvTotalReg);\n' ...
    '    done=true;\n' ...
    'end\n' ...
    'valid=validReg; totalMetricNew=totalReg; cmvMetricNew=cmvTotalReg;\n' ...
    'cmvIncrement=incrementReg; iabcNext=iabcReg; deltaStep=stepReg;\n' ...
    'deltaDead=deadReg; lowerBound=lowerReg; upperBound=upperReg;\n' ...
    'deadtimeMiss=missReg;\n' ...
    'end\n\n' ...
    'function [deltaStep,deltaDead]=deadtime_step(sPrevious,sCurrent,iabc,problem)\n' ...
    'sDead=sCurrent; signEps=0.1*problem.currentEpsMargin;\n' ...
    'for phase=1:3\n' ...
    '    if sPrevious(phase)~=sCurrent(phase)\n' ...
    '        if iabc(phase)>=signEps\n' ...
    '            sDead(phase)=0.0;\n' ...
    '        elseif iabc(phase)<=-signEps\n' ...
    '            sDead(phase)=1.0;\n' ...
    '        elseif signEps>0.0\n' ...
    '            sDead(phase)=0.5*(1.0-iabc(phase)/signEps);\n' ...
    '        else\n' ...
    '            sDead(phase)=0.5;\n' ...
    '        end\n' ...
    '    end\n' ...
    'end\n' ...
    'sEffective=problem.deadtimeRatio*sDead+(1.0-problem.deadtimeRatio)*sCurrent;\n' ...
    'deltaDead=problem.deadtimeRatio*(problem.deltaIabcBase+problem.deltaIabcSwitch*sDead);\n' ...
    'deltaStep=problem.deltaIabcBase+problem.deltaIabcSwitch*sEffective;\n' ...
    'end\n\n' ...
    'function [penalty,lower,upper,deadtimeMiss]=cmv_penalty(sPrevious,sCurrent,iabc,deltaDead,problem)\n' ...
    'penalty=0.0; deadtimeMiss=false; iabcEnd=iabc+deltaDead;\n' ...
    'lower=min(iabc,iabcEnd)-problem.currentEpsMargin;\n' ...
    'upper=max(iabc,iabcEnd)+problem.currentEpsMargin;\n' ...
    'uncertain=(lower<=0.0)&(upper>=0.0);\n' ...
    'if all(sCurrent==0.0)||all(sCurrent==1.0)\n' ...
    '    penalty=penalty+problem.lambdaZero;\n' ...
    'end\n' ...
    'changed=(sPrevious~=sCurrent);\n' ...
    'if sum(changed)==2\n' ...
    '    canZero=false(3,1); canOne=false(3,1);\n' ...
    '    for phase=1:3\n' ...
    '        if ~changed(phase)\n' ...
    '            canZero(phase)=sPrevious(phase)==0.0;\n' ...
    '            canOne(phase)=sPrevious(phase)==1.0;\n' ...
    '        elseif uncertain(phase)\n' ...
    '            canZero(phase)=true; canOne(phase)=true;\n' ...
    '        elseif iabcEnd(phase)>0.0\n' ...
    '            canZero(phase)=true;\n' ...
    '        else\n' ...
    '            canOne(phase)=true;\n' ...
    '        end\n' ...
    '    end\n' ...
    '    deadtimeMiss=all(canZero)||all(canOne);\n' ...
    '    if deadtimeMiss\n' ...
    '        penalty=penalty+problem.lambdaDeadtime;\n' ...
    '    end\n' ...
    'end\n' ...
    'end\n']);
end

function code = branch_memory_code()
code = sprintf([ ...
    'function [memory,candidateExhausted] = BranchMemory(clear,initWrite,pathWrite,vectorWrite,level,fsmState,candidate,quadraticMetric,vectorMetric,cmvMetric,iabcNext,z,iabcInitial)\n' ...
    '%%#codegen\n' ...
    'persistent state\n' ...
    'if isempty(state)\n' ...
    '    state.Uwork=false(15,1);\n' ...
    '    state.candidatePosition=ones(15,1,''uint8'');\n' ...
    '    state.metricStack=zeros(16,1); state.cmvMetricStack=zeros(16,1);\n' ...
    '    state.iabcPrediction=zeros(3,6); state.z=zeros(15,1);\n' ...
    'end\n' ...
    'idx=max(uint8(1),min(uint8(15),level));\n' ...
    'if clear\n' ...
    '    state.Uwork(:)=false; state.candidatePosition(:)=uint8(1);\n' ...
    '    state.metricStack(:)=0.0; state.cmvMetricStack(:)=0.0;\n' ...
    '    state.iabcPrediction(:)=0.0; state.z(:)=0.0;\n' ...
    'end\n' ...
    'if initWrite\n' ...
    '    state.z=z; state.iabcPrediction(:,1)=iabcInitial;\n' ...
    '    state.metricStack(1)=0.0; state.cmvMetricStack(1)=0.0;\n' ...
    'end\n' ...
    'if pathWrite\n' ...
    '    if fsmState==uint8(7)\n' ...
    '        state.Uwork(idx)=candidate;\n' ...
    '        state.candidatePosition(idx)=state.candidatePosition(idx)+uint8(1);\n' ...
    '        state.metricStack(double(idx)+1)=quadraticMetric;\n' ...
    '        state.cmvMetricStack(double(idx)+1)=state.cmvMetricStack(double(idx));\n' ...
    '    elseif fsmState==uint8(15)\n' ...
    '        state.candidatePosition(idx)=uint8(1);\n' ...
    '    elseif fsmState==uint8(17)\n' ...
    '        resetIdx=min(uint8(15),idx+uint8(1));\n' ...
    '        state.candidatePosition(resetIdx)=uint8(1);\n' ...
    '    end\n' ...
    'end\n' ...
    'if vectorWrite\n' ...
    '    state.metricStack(double(idx)+1)=vectorMetric;\n' ...
    '    state.cmvMetricStack(double(idx)+1)=cmvMetric;\n' ...
    '    predictionStep=idivide(idx,uint8(3));\n' ...
    '    currentColumn=min(6,double(predictionStep)+1);\n' ...
    '    state.iabcPrediction(:,currentColumn)=iabcNext;\n' ...
    'end\n' ...
    'candidateExhausted=state.candidatePosition(idx)>uint8(2);\n' ...
    'memory=state;\n' ...
    'end\n']);
end
