function implement_sda_stage2()
%IMPLEMENT_SDA_STAGE2 Add quadratic node calculation and branch writes.

rootDir = fileparts(mfilename('fullpath'));
modelFile = fullfile(rootDir, 'FCSMPC_double_vector.slx');
model = 'FCSMPC_double_vector';
base = [model '/FCS_MPC/SDA_Solve/SDA Solve/SDA/' ...
    'double_vector_matlab_FSM_Calc/SDA_Solve/PL_Framework'];

backupDir = fullfile(rootDir, 'backups');
if ~isfolder(backupDir), mkdir(backupDir); end
stamp = datestr(now, 'yyyymmdd_HHMMSS');
copyfile(modelFile, fullfile(backupDir, ...
    ['FCSMPC_double_vector_before_stage2_' stamp '.slx']));

load_system(modelFile);
cleanup = onCleanup(@() close_system(model, 0));
sf = sfroot;

quadPath = [base '/QuadraticCalc'];
branchPath = [base '/BranchMemory'];
quad = sf.find('-isa', 'Stateflow.EMChart', 'Path', quadPath);
branch = sf.find('-isa', 'Stateflow.EMChart', 'Path', branchPath);
quad.Script = quadratic_code();
branch.Script = branch_memory_code();

set_data(quad, 'problem', 'Bus: SdaProblemBus', '[1 1]');
set_data(quad, 'start', 'boolean', '[1 1]');
set_data(quad, 'level', 'uint8', '[1 1]');
set_data(quad, 'memory', 'Bus: SdaMemoryBus', '[1 1]');
set_data(quad, 'done', 'boolean', '[1 1]');
set_data(quad, 'valid', 'boolean', '[1 1]');
set_data(quad, 'metricNew', 'double', '[1 1]');
set_data(quad, 'head', 'double', '[1 1]');
set_data(quad, 'center', 'double', '[1 1]');
set_data(quad, 'firstCandidate', 'boolean', '[1 1]');
set_data(quad, 'candidate', 'boolean', '[1 1]');
set_data(quad, 'residual', 'double', '[1 1]');

branchInputs = { ...
    'clear','boolean','[1 1]'; ...
    'initWrite','boolean','[1 1]'; ...
    'writeEnable','boolean','[1 1]'; ...
    'level','uint8','[1 1]'; ...
    'fsmState','uint8','[1 1]'; ...
    'candidate','boolean','[1 1]'; ...
    'metricNew','double','[1 1]'; ...
    'z','double','[15 1]'; ...
    'iabcInitial','double','[3 1]'};
for k = 1:size(branchInputs,1)
    set_data(branch, branchInputs{k,1}, branchInputs{k,2}, ...
        branchInputs{k,3});
end
set_data(branch, 'memory', 'Bus: SdaMemoryBus', '[1 1]');
set_data(branch, 'candidateExhausted', 'boolean', '[1 1]');

% Rebuild QuadraticCalc inputs after removing the obsolete candidate input.
disconnect_all_inputs(quadPath);
connect(base, 'ProblemLatch', 1, 'QuadraticCalc', 1);
connect(base, 'SearchFSM', 3, 'QuadraticCalc', 2);
connect(base, 'SearchFSM', 12, 'QuadraticCalc', 3);
connect(base, 'BranchMemoryStateDelay', 1, 'QuadraticCalc', 4);

% Rebuild BranchMemory command and data inputs.
disconnect_all_inputs(branchPath);
connect(base, 'SearchFSM', 5, 'BranchMemory', 1);       % clear
connect(base, 'SdaInitializer', 1, 'BranchMemory', 2);  % initWrite
connect(base, 'SearchFSM', 6, 'BranchMemory', 3);       % branch write
connect(base, 'SearchFSM', 12, 'BranchMemory', 4);      % level
connect(base, 'SearchFSM', 14, 'BranchMemory', 5);      % fsmState
connect(base, 'QuadraticCalc', 7, 'BranchMemory', 6);   % candidate
connect(base, 'QuadraticCalc', 3, 'BranchMemory', 7);   % metricNew
connect(base, 'SdaInitializer', 3, 'BranchMemory', 8);  % z
connect(base, 'iabcCompensated', 1, 'BranchMemory', 9);

% The old OR gate is no longer required because initialization and node
% writes now have separate explicit ports.
orPath = [base '/BranchWriteOr'];
if getSimulinkBlockHandle(orPath) > 0
    delete_block(orPath);
end

chartPath = [base '/SearchFSM'];
chart = sf.find('-isa', 'Stateflow.Chart', 'Path', chartPath);
add_chart_input(chart, 'quadCandidate', 8, 'boolean');
add_chart_input(chart, 'candidateExhausted', 9, 'boolean');

candidateDelay = [base '/QuadCandidateDelay'];
if getSimulinkBlockHandle(candidateDelay) <= 0
    add_block('simulink/Discrete/Unit Delay', candidateDelay, ...
        'InitialCondition', 'false', ...
        'Position', [690 340 725 370]);
end
connect_if_free(base, 'QuadraticCalc', 7, 'QuadCandidateDelay', 1);
connect_if_free(base, 'QuadCandidateDelay', 1, 'SearchFSM', 8);

exhaustedDelay = [base '/CandidateExhaustedDelay'];
if getSimulinkBlockHandle(exhaustedDelay) <= 0
    add_block('simulink/Discrete/Unit Delay', exhaustedDelay, ...
        'InitialCondition', 'false', ...
        'Position', [1015 470 1050 500]);
end
connect_if_free(base, 'BranchMemory', 2, 'CandidateExhaustedDelay', 1);
connect_if_free(base, 'CandidateExhaustedDelay', 1, 'SearchFSM', 9);

% State actions: Stateflow commands, calculation result supplies data.
set_state(chart, 'SELECT_CANDIDATE', ...
    ['SELECT_CANDIDATE' newline ...
    'entry: fsmState=uint8(7); candidate=quadCandidate; memWrite=true;']);
set_state(chart, 'METRIC_START', ...
    ['METRIC_START' newline 'entry: fsmState=uint8(8);']);
set_state(chart, 'METRIC_WAIT', ...
    ['METRIC_WAIT' newline 'entry: fsmState=uint8(9);']);
set_state(chart, 'CHECK_LEVEL', ...
    ['CHECK_LEVEL' newline 'entry: fsmState=uint8(4);']);
set_state(chart, 'DESCEND', ...
    ['DESCEND' newline ...
    'entry: fsmState=uint8(15); level=level+uint8(1); memWrite=true;']);
set_state(chart, 'BACKTRACK', ...
    ['BACKTRACK' newline ...
    'entry: fsmState=uint8(17); if level>uint8(0); level=level-uint8(1); end; memWrite=true;']);

% CHECK_LEVEL is now a guarded decision instead of an unconditional path.
set_transition(chart, 'CHECK_LEVEL', 'CENTER_START', ...
    '[~candidateExhausted]');
ensure_transition(chart, 'CHECK_LEVEL', 'BACKTRACK', ...
    '[candidateExhausted]');

% Metric was computed by the CENTER request and is held in QuadraticCalc.
set_transition(chart, 'METRIC_WAIT', 'VECTOR_CHECK', '');

% Expose the extra arithmetic values without changing the public interface.
add_terminator(base, 'QuadFirstCandidateTerminator', ...
    'QuadraticCalc', 6, [675 285 695 305]);
add_terminator(base, 'QuadResidualTerminator', ...
    'QuadraticCalc', 8, [675 315 695 335]);

set_param(model, 'SimulationCommand', 'update');
save_system(model, modelFile);
fprintf('SDA stage 2 implemented and model updated successfully.\n');
end

function set_data(chart, name, type, sizeText)
data = chart.find('-isa', 'Stateflow.Data', 'Name', name);
if isempty(data), error('Missing data %s in %s', name, chart.Path); end
data.DataType = type;
data.Props.Array.Size = sizeText;
end

function add_chart_input(chart, name, port, type)
data = chart.find('-isa', 'Stateflow.Data', 'Name', name);
if isempty(data)
    data = Stateflow.Data(chart);
    data.Name = name;
    data.Scope = 'Input';
end
data.Port = port;
data.DataType = type;
data.Props.Array.Size = '[1 1]';
end

function disconnect_all_inputs(path)
ports = get_param(path, 'PortHandles');
for k = 1:numel(ports.Inport)
    line = get_param(ports.Inport(k), 'Line');
    if line ~= -1, delete_line(line); end
end
end

function connect(parent, srcName, srcPort, dstName, dstPort)
src = get_param([parent '/' srcName], 'PortHandles');
dst = get_param([parent '/' dstName], 'PortHandles');
add_line(parent, src.Outport(srcPort), dst.Inport(dstPort), ...
    'autorouting', 'on');
end

function connect_if_free(parent, srcName, srcPort, dstName, dstPort)
dst = get_param([parent '/' dstName], 'PortHandles');
if get_param(dst.Inport(dstPort), 'Line') == -1
    connect(parent, srcName, srcPort, dstName, dstPort);
end
end

function set_state(chart, name, label)
state = chart.find('-isa', 'Stateflow.State', 'Name', name);
if isempty(state), error('Missing Stateflow state: %s', name); end
state.LabelString = label;
end

function set_transition(chart, sourceName, destinationName, label)
transition = find_transition(chart, sourceName, destinationName);
if isempty(transition)
    error('Missing transition %s -> %s', sourceName, destinationName);
end
transition.LabelString = label;
end

function ensure_transition(chart, sourceName, destinationName, label)
transition = find_transition(chart, sourceName, destinationName);
if isempty(transition)
    source = chart.find('-isa', 'Stateflow.State', 'Name', sourceName);
    destination = chart.find('-isa', 'Stateflow.State', 'Name', destinationName);
    transition = Stateflow.Transition(chart);
    transition.Source = source;
    transition.Destination = destination;
    transition.SourceOClock = 3;
    transition.DestinationOClock = 9;
end
transition.LabelString = label;
end

function transition = find_transition(chart, sourceName, destinationName)
transition = [];
allTransitions = chart.find('-isa', 'Stateflow.Transition');
for k = 1:numel(allTransitions)
    item = allTransitions(k);
    if ~isempty(item.Source) && ~isempty(item.Destination) && ...
            strcmp(item.Source.Name, sourceName) && ...
            strcmp(item.Destination.Name, destinationName)
        transition = item;
        return;
    end
end
end

function add_terminator(parent, name, srcName, srcPort, position)
path = [parent '/' name];
if getSimulinkBlockHandle(path) > 0, return; end
src = get_param([parent '/' srcName], 'PortHandles');
if get_param(src.Outport(srcPort), 'Line') ~= -1, return; end
add_block('simulink/Sinks/Terminator', path, 'Position', position);
dst = get_param(path, 'PortHandles');
add_line(parent, src.Outport(srcPort), dst.Inport(1), ...
    'autorouting', 'on');
end

function code = quadratic_code()
code = sprintf([ ...
    'function [done, valid, metricNew, head, center, firstCandidate, candidate, residual] = QuadraticCalc(problem, start, level, memory)\n' ...
    '%%#codegen\n' ...
    'persistent metricReg headReg centerReg firstReg candidateReg residualReg validReg\n' ...
    'if isempty(metricReg)\n' ...
    '    metricReg=0.0; headReg=0.0; centerReg=0.0;\n' ...
    '    firstReg=false; candidateReg=false; residualReg=0.0; validReg=false;\n' ...
    'end\n' ...
    'done=false;\n' ...
    'if start\n' ...
    '    idx=max(uint8(1),min(uint8(15),level));\n' ...
    '    row=double(idx); headReg=0.0;\n' ...
    '    for k=1:15\n' ...
    '        if k<row\n' ...
    '            headReg=headReg+problem.H(row,k)*double(memory.Uwork(k));\n' ...
    '        end\n' ...
    '    end\n' ...
    '    diagonal=problem.H(row,row);\n' ...
    '    validReg=isfinite(diagonal)&&abs(diagonal)>1e-12;\n' ...
    '    if validReg\n' ...
    '        centerReg=(memory.z(row)-headReg)/diagonal;\n' ...
    '        firstReg=centerReg>0.5;\n' ...
    '        if memory.candidatePosition(row)==uint8(1)\n' ...
    '            candidateReg=firstReg;\n' ...
    '        else\n' ...
    '            candidateReg=~firstReg;\n' ...
    '        end\n' ...
    '        residualReg=memory.z(row)-headReg-diagonal*double(candidateReg);\n' ...
    '        metricReg=memory.metricStack(row)+residualReg*residualReg;\n' ...
    '        validReg=isfinite(centerReg)&&isfinite(metricReg);\n' ...
    '    else\n' ...
    '        centerReg=0.0; firstReg=false; candidateReg=false;\n' ...
    '        residualReg=0.0; metricReg=realmax;\n' ...
    '    end\n' ...
    '    done=true;\n' ...
    'end\n' ...
    'valid=validReg; metricNew=metricReg; head=headReg; center=centerReg;\n' ...
    'firstCandidate=firstReg; candidate=candidateReg; residual=residualReg;\n' ...
    'end\n']);
end

function code = branch_memory_code()
code = sprintf([ ...
    'function [memory,candidateExhausted] = BranchMemory(clear,initWrite,writeEnable,level,fsmState,candidate,metricNew,z,iabcInitial)\n' ...
    '%%#codegen\n' ...
    'persistent state\n' ...
    'if isempty(state)\n' ...
    '    state.Uwork=false(15,1);\n' ...
    '    state.candidatePosition=ones(15,1,''uint8'');\n' ...
    '    state.metricStack=zeros(16,1); state.cmvMetricStack=zeros(16,1);\n' ...
    '    state.iabcPrediction=zeros(3,6); state.z=zeros(15,1);\n' ...
    'end\n' ...
    'idx=max(uint8(1),min(uint8(15),level));\n' ...
    'if clear\n' ...
    '    state.Uwork(:)=false; state.candidatePosition(:)=uint8(1);\n' ...
    '    state.metricStack(:)=0.0; state.cmvMetricStack(:)=0.0;\n' ...
    '    state.iabcPrediction(:)=0.0; state.z(:)=0.0;\n' ...
    'end\n' ...
    'if initWrite\n' ...
    '    state.z=z; state.iabcPrediction(:,1)=iabcInitial;\n' ...
    '    state.metricStack(1)=0.0; state.cmvMetricStack(1)=0.0;\n' ...
    'end\n' ...
    'if writeEnable\n' ...
    '    if fsmState==uint8(7)\n' ...
    '        state.Uwork(idx)=candidate;\n' ...
    '        state.candidatePosition(idx)=state.candidatePosition(idx)+uint8(1);\n' ...
    '        state.metricStack(double(idx)+1)=metricNew;\n' ...
    '    elseif fsmState==uint8(15)\n' ...
    '        state.candidatePosition(idx)=uint8(1);\n' ...
    '    elseif fsmState==uint8(17)\n' ...
    '        resetIdx=min(uint8(15),idx+uint8(1));\n' ...
    '        state.candidatePosition(resetIdx)=uint8(1);\n' ...
    '    end\n' ...
    'end\n' ...
    'candidateExhausted=state.candidatePosition(idx)>uint8(2);\n' ...
    'memory=state;\n' ...
    'end\n']);
end
