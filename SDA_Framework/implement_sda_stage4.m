function implement_sda_stage4()
%IMPLEMENT_SDA_STAGE4 Close search, best-result, counters, and result commit.

rootDir = fileparts(mfilename('fullpath'));
modelFile = fullfile(rootDir, 'FCSMPC_double_vector.slx');
model = 'FCSMPC_double_vector';
base = [model '/FCS_MPC/SDA_Solve/SDA Solve/SDA/' ...
    'double_vector_matlab_FSM_Calc/SDA_Solve/PL_Framework'];

backupDir = fullfile(rootDir, 'backups');
if ~isfolder(backupDir), mkdir(backupDir); end
stamp = datestr(now, 'yyyymmdd_HHMMSS');
copyfile(modelFile, fullfile(backupDir, ...
    ['FCSMPC_double_vector_before_stage4_' stamp '.slx']));

load_system(modelFile);
cleanup = onCleanup(@() close_system(model, 0));
sf = sfroot;

add_eml(base, 'MetricCompare', [1075 315 1245 430], ...
    metric_compare_code());
add_eml(base, 'SearchCounter', [1075 445 1245 550], ...
    search_counter_code());

bestPath = [base '/BestMemory'];
resultPath = [base '/ResultCommit'];
best = sf.find('-isa', 'Stateflow.EMChart', 'Path', bestPath);
result = sf.find('-isa', 'Stateflow.EMChart', 'Path', resultPath);
best.Script = best_memory_code();
result.Script = result_commit_code();

configure_interfaces(sf, base);

% BestMemory: independent initialization and search-update channels.
disconnect_all_inputs(bestPath);
connect(base, 'SdaInitializer', 1, 'BestMemory', 1); % initWrite
connect(base, 'SearchFSM', 7, 'BestMemory', 2);      % searchWrite
connect(base, 'SdaInitializer', 4, 'BestMemory', 3);
connect(base, 'SdaInitializer', 5, 'BestMemory', 4);
connect(base, 'SdaInitializer', 6, 'BestMemory', 5);
connect(base, 'BranchMemoryStateDelay', 1, 'BestMemory', 6);
connect(base, 'MetricCompare', 1, 'BestMemory', 7);
connect(base, 'MetricCompare', 2, 'BestMemory', 8);

% Explicitly register the best-result feedback.  BestMemory updates state,
% while MetricCompare consumes the previous-cycle snapshot; this removes an
% algebraic loop and matches the intended FPGA register boundary.
bestDelayPath = [base '/BestMemoryStateDelay'];
if getSimulinkBlockHandle(bestDelayPath) <= 0
    add_block('simulink/Discrete/Unit Delay', bestDelayPath, ...
        'InitialCondition', '0', 'Position', [1015 555 1050 585]);
end
disconnect_all_inputs(bestDelayPath);
connect(base, 'BestMemory', 1, 'BestMemoryStateDelay', 1);

% Metric selection after quadratic/vector stages.
connect_all_metric_compare(base);

% Search accounting: candidate visits, leaves, and node-budget overflow.
connect(base, 'SearchFSM', 5, 'SearchCounter', 1);
connect(base, 'SearchFSM', 6, 'SearchCounter', 2);
connect(base, 'SearchFSM', 14, 'SearchCounter', 3);
connect(base, 'SearchFSM', 12, 'SearchCounter', 4);
connect(base, 'ProblemLatch', 1, 'SearchCounter', 5);

chart = sf.find('-isa', 'Stateflow.Chart', 'Path', [base '/SearchFSM']);
add_chart_input(chart, 'currentBetter', 10, 'boolean');
add_chart_input(chart, 'currentPrune', 11, 'boolean');
add_chart_input(chart, 'nodeLimitReached', 12, 'boolean');

% Registered decisions into Stateflow.  Add chart inputs first so their
% Simulink ports exist before connecting the delay blocks.
add_status_delay(base, 'MetricBetterDelay', 'MetricCompare', 3, ...
    'SearchFSM', 10, 'false', [1265 330 1300 360]);
add_status_delay(base, 'MetricPruneDelay', 'MetricCompare', 4, ...
    'SearchFSM', 11, 'false', [1265 375 1300 405]);
add_status_delay(base, 'NodeLimitDelay', 'SearchCounter', 3, ...
    'SearchFSM', 12, 'false', [1265 475 1300 505]);

% Mutually exclusive decision guards.
set_transition(chart, 'CHECK_LEVEL', 'CENTER_START', ...
    '[~nodeLimitReached && ~candidateExhausted]');
set_transition(chart, 'CHECK_LEVEL', 'BACKTRACK', ...
    '[~nodeLimitReached && candidateExhausted]');
ensure_transition(chart, 'CHECK_LEVEL', 'WRITE_RESULT', ...
    '[nodeLimitReached]');

set_transition(chart, 'COMPARE', 'DESCEND', ...
    '[level<uint8(15) && ~currentPrune]');
set_transition(chart, 'COMPARE', 'UPDATE_BEST', ...
    '[level==uint8(15) && currentBetter]');
ensure_transition(chart, 'COMPARE', 'NEXT_CANDIDATE', ...
    '[currentPrune || (level==uint8(15) && ~currentBetter)]');

% After either prune or leaf handling, try the other candidate at the same
% level. CHECK_LEVEL alone decides when the level is exhausted.
retarget_transition(chart, 'NEXT_CANDIDATE', 'BACKTRACK', ...
    'NEXT_CANDIDATE', 'CHECK_LEVEL', '');

% ResultCommit inputs and transaction-level output register.
disconnect_all_inputs(resultPath);
connect(base, 'ProblemLatch', 1, 'ResultCommit', 1);
connect(base, 'SearchFSM', 8, 'ResultCommit', 2);
connect(base, 'BestMemory', 1, 'ResultCommit', 3);
connect(base, 'SearchCounter', 1, 'ResultCommit', 4);
connect(base, 'SearchCounter', 2, 'ResultCommit', 5);
connect(base, 'SearchCounter', 3, 'ResultCommit', 6);
connect(base, 'SdaInitializer', 7, 'ResultCommit', 7);
connect(base, 'SdaInitializer', 8, 'ResultCommit', 8);

% Initializer diagnostics now feed ResultCommit, so remove old terminators.
delete_if_present([base '/InitJroundTerminator']);
delete_if_present([base '/InitJshiftTerminator']);

set_param(model, 'SimulationCommand', 'update');
save_system(model, modelFile);
fprintf('SDA stage 4 implemented and model updated successfully.\n');
end

function configure_interfaces(sf, base)
metric = sf.find('-isa', 'Stateflow.EMChart', 'Path', [base '/MetricCompare']);
set_data(metric,'level','uint8','[1 1]');
set_data(metric,'quadraticMetric','double','[1 1]');
set_data(metric,'vectorMetric','double','[1 1]');
set_data(metric,'vectorCmvMetric','double','[1 1]');
set_data(metric,'memory','Bus: SdaMemoryBus','[1 1]');
set_data(metric,'best','Bus: SdaBestBus','[1 1]');
set_data(metric,'currentMetric','double','[1 1]');
set_data(metric,'currentCmvMetric','double','[1 1]');
set_data(metric,'better','boolean','[1 1]');
set_data(metric,'prune','boolean','[1 1]');

counter = sf.find('-isa','Stateflow.EMChart','Path',[base '/SearchCounter']);
set_data(counter,'clear','boolean','[1 1]');
set_data(counter,'writeEnable','boolean','[1 1]');
set_data(counter,'fsmState','uint8','[1 1]');
set_data(counter,'level','uint8','[1 1]');
set_data(counter,'problem','Bus: SdaProblemBus','[1 1]');
set_data(counter,'nodes','uint32','[1 1]');
set_data(counter,'leafNodes','uint32','[1 1]');
set_data(counter,'nodeLimitReached','boolean','[1 1]');

best = sf.find('-isa','Stateflow.EMChart','Path',[base '/BestMemory']);
bestInputs = { ...
 'initWrite','boolean','[1 1]'; 'searchWrite','boolean','[1 1]'; ...
 'initialU','double','[15 1]'; 'initialMetric','double','[1 1]'; ...
 'initialCmv','double','[1 1]'; 'memory','Bus: SdaMemoryBus','[1 1]'; ...
 'candidateMetric','double','[1 1]'; 'candidateCmv','double','[1 1]'};
for k=1:size(bestInputs,1)
 set_data(best,bestInputs{k,1},bestInputs{k,2},bestInputs{k,3});
end
set_data(best,'best','Bus: SdaBestBus','[1 1]');

result=sf.find('-isa','Stateflow.EMChart','Path',[base '/ResultCommit']);
resultInputs={ ...
 'problem','Bus: SdaProblemBus','[1 1]'; 'commit','boolean','[1 1]'; ...
 'best','Bus: SdaBestBus','[1 1]'; 'nodes','uint32','[1 1]'; ...
 'leafNodes','uint32','[1 1]'; 'nodeLimitReached','boolean','[1 1]'; ...
 'Jround','double','[1 1]'; 'Jshift','double','[1 1]'};
for k=1:size(resultInputs,1)
 set_data(result,resultInputs{k,1},resultInputs{k,2},resultInputs{k,3});
end
set_data(result,'result','Bus: SdaResultBus','[1 1]');
end

function add_eml(parent,name,position,script)
path=[parent '/' name];
if getSimulinkBlockHandle(path)<=0
 add_block('simulink/User-Defined Functions/MATLAB Function',path, ...
  'Position',position);
end
sf=sfroot; chart=sf.find('-isa','Stateflow.EMChart','Path',path);
chart.Script=script;
end

function connect_all_metric_compare(base)
path=[base '/MetricCompare']; disconnect_all_inputs(path);
connect(base,'SearchFSM',12,'MetricCompare',1);
connect(base,'QuadraticCalc',3,'MetricCompare',2);
connect(base,'VectorCostCalc',3,'MetricCompare',3);
connect(base,'VectorCostCalc',4,'MetricCompare',4);
connect(base,'BranchMemoryStateDelay',1,'MetricCompare',5);
connect(base,'BestMemoryStateDelay',1,'MetricCompare',6);
end

function add_status_delay(base,name,srcName,srcPort,dstName,dstPort,ic,pos)
path=[base '/' name];
if getSimulinkBlockHandle(path)<=0
 add_block('simulink/Discrete/Unit Delay',path,'InitialCondition',ic, ...
  'Position',pos);
end
connect_if_free(base,srcName,srcPort,name,1);
connect_if_free(base,name,1,dstName,dstPort);
end

function set_data(chart,name,type,sizeText)
data=chart.find('-isa','Stateflow.Data','Name',name);
if isempty(data), error('Missing data %s in %s',name,chart.Path); end
data.DataType=type; data.Props.Array.Size=sizeText;
end

function add_chart_input(chart,name,port,type)
data=chart.find('-isa','Stateflow.Data','Name',name);
if isempty(data), data=Stateflow.Data(chart); data.Name=name; data.Scope='Input'; end
data.Port=port; data.DataType=type; data.Props.Array.Size='[1 1]';
end

function disconnect_all_inputs(path)
ports=get_param(path,'PortHandles');
for k=1:numel(ports.Inport)
 line=get_param(ports.Inport(k),'Line'); if line~=-1, delete_line(line); end
end
end

function connect(parent,srcName,srcPort,dstName,dstPort)
src=get_param([parent '/' srcName],'PortHandles');
dst=get_param([parent '/' dstName],'PortHandles');
add_line(parent,src.Outport(srcPort),dst.Inport(dstPort),'autorouting','on');
end

function connect_if_free(parent,srcName,srcPort,dstName,dstPort)
dst=get_param([parent '/' dstName],'PortHandles');
if get_param(dst.Inport(dstPort),'Line')==-1
 connect(parent,srcName,srcPort,dstName,dstPort);
end
end

function set_transition(chart,sourceName,destinationName,label)
t=find_transition(chart,sourceName,destinationName);
if isempty(t), error('Missing transition %s -> %s',sourceName,destinationName); end
t.LabelString=label;
end

function ensure_transition(chart,sourceName,destinationName,label)
t=find_transition(chart,sourceName,destinationName);
if isempty(t)
 source=chart.find('-isa','Stateflow.State','Name',sourceName);
 destination=chart.find('-isa','Stateflow.State','Name',destinationName);
 t=Stateflow.Transition(chart); t.Source=source; t.Destination=destination;
 t.SourceOClock=3; t.DestinationOClock=9;
end
t.LabelString=label;
end

function retarget_transition(chart,oldSource,oldDestination,newSource,newDestination,label)
t=find_transition(chart,oldSource,oldDestination);
if isempty(t), error('Missing transition %s -> %s',oldSource,oldDestination); end
t.Source=chart.find('-isa','Stateflow.State','Name',newSource);
t.Destination=chart.find('-isa','Stateflow.State','Name',newDestination);
t.LabelString=label;
end

function t=find_transition(chart,sourceName,destinationName)
t=[]; all=chart.find('-isa','Stateflow.Transition');
for k=1:numel(all)
 item=all(k);
 if ~isempty(item.Source)&&~isempty(item.Destination)&& ...
   strcmp(item.Source.Name,sourceName)&&strcmp(item.Destination.Name,destinationName)
  t=item; return;
 end
end
end

function delete_if_present(path)
if getSimulinkBlockHandle(path)>0, delete_block(path); end
end

function code=metric_compare_code()
code=sprintf([ ...
'function [currentMetric,currentCmvMetric,better,prune] = MetricCompare(level,quadraticMetric,vectorMetric,vectorCmvMetric,memory,best)\n' ...
'%%#codegen\n' ...
'idx=max(uint8(1),min(uint8(15),level));\n' ...
'if mod(idx,uint8(3))==uint8(0)\n' ...
' currentMetric=vectorMetric; currentCmvMetric=vectorCmvMetric;\n' ...
'else\n' ...
' currentMetric=quadraticMetric;\n' ...
' currentCmvMetric=memory.cmvMetricStack(double(idx)+1);\n' ...
'end\n' ...
'better=currentMetric<best.bestMetric;\n' ...
'prune=currentMetric>best.bestMetric;\n' ...
'end\n']);
end

function code=search_counter_code()
code=sprintf([ ...
'function [nodes,leafNodes,nodeLimitReached] = SearchCounter(clear,writeEnable,fsmState,level,problem)\n' ...
'%%#codegen\n' ...
'persistent nodeReg leafReg limitReg\n' ...
'if isempty(nodeReg), nodeReg=uint32(0); leafReg=uint32(0); limitReg=false; end\n' ...
'if clear, nodeReg=uint32(0); leafReg=uint32(0); limitReg=false; end\n' ...
'if writeEnable&&fsmState==uint8(7)\n' ...
' nodeReg=nodeReg+uint32(1);\n' ...
' if level==uint8(15), leafReg=leafReg+uint32(1); end\n' ...
' if problem.NmaxNode>uint32(0)&&nodeReg>problem.NmaxNode, limitReg=true; end\n' ...
'end\n' ...
'nodes=nodeReg; leafNodes=leafReg; nodeLimitReached=limitReg;\n' ...
'end\n']);
end

function code=best_memory_code()
code=sprintf([ ...
'function best = BestMemory(initWrite,searchWrite,initialU,initialMetric,initialCmv,memory,candidateMetric,candidateCmv)\n' ...
'%%#codegen\n' ...
'persistent state\n' ...
'if isempty(state)\n' ...
' state.bestU=false(15,1); state.bestMetric=realmax;\n' ...
' state.bestCMVCost=0.0; state.bestValid=false;\n' ...
'end\n' ...
'if initWrite\n' ...
' state.bestU=initialU>0.5; state.bestMetric=initialMetric;\n' ...
' state.bestCMVCost=initialCmv; state.bestValid=isfinite(initialMetric);\n' ...
'elseif searchWrite&&candidateMetric<state.bestMetric\n' ...
' state.bestU=memory.Uwork; state.bestMetric=candidateMetric;\n' ...
' state.bestCMVCost=candidateCmv; state.bestValid=isfinite(candidateMetric);\n' ...
'end\n' ...
'best=state;\n' ...
'end\n']);
end

function code=result_commit_code()
code=sprintf([ ...
'function result = ResultCommit(problem,commit,best,nodes,leafNodes,nodeLimitReached,Jround,Jshift)\n' ...
'%%#codegen\n' ...
'persistent state\n' ...
'if isempty(state)\n' ...
' state.valid=false; state.Jopt=realmax; state.nodes=uint32(0);\n' ...
' state.optimal=false; state.Uopt=zeros(15,1); state.Uapply=zeros(6,1);\n' ...
' state.leafNodes=uint32(0); state.bestCMVCost=0.0; state.cmvMetricRatio=0.0;\n' ...
' state.switchCountApplied=uint32(0); state.debugLower=zeros(3,1);\n' ...
' state.debugUpper=zeros(3,1); state.iabcPredictedNext=zeros(3,1);\n' ...
' state.Jround=0.0; state.Jshift=0.0; state.predictionValidNext=false;\n' ...
'end\n' ...
'if commit\n' ...
' state.valid=best.bestValid; state.Jopt=best.bestMetric;\n' ...
' state.nodes=nodes; state.leafNodes=leafNodes;\n' ...
' state.optimal=best.bestValid&&~nodeLimitReached;\n' ...
' state.Uopt=double(best.bestU); state.Uapply=state.Uopt(1:6);\n' ...
' state.bestCMVCost=best.bestCMVCost;\n' ...
' if state.Jopt>eps, state.cmvMetricRatio=state.bestCMVCost/state.Jopt; else, state.cmvMetricRatio=0.0; end\n' ...
' sPrev=problem.UoptPrev(4:6); sFirst=state.Uopt(1:3); sSecond=state.Uopt(4:6);\n' ...
' [deltaFirst,deltaDead]=deadtime_step(sPrev,sFirst,problem.iabcCompensated,problem);\n' ...
' iabcAfter=problem.iabcCompensated+deltaFirst;\n' ...
' [deltaSecond,~]=deadtime_step(sFirst,sSecond,iabcAfter,problem);\n' ...
' state.iabcPredictedNext=iabcAfter+deltaSecond;\n' ...
' state.switchCountApplied=uint32(sum(abs(sFirst-sPrev))+sum(abs(sSecond-sFirst)));\n' ...
' [~,state.debugLower,state.debugUpper]=cmv_bounds(problem.iabcCompensated,deltaDead,problem.currentEpsMargin);\n' ...
' state.Jround=Jround; state.Jshift=Jshift; state.predictionValidNext=best.bestValid;\n' ...
'end\n' ...
'result=state;\n' ...
'end\n\n' ...
'function [deltaStep,deltaDead]=deadtime_step(sPrevious,sCurrent,iabc,problem)\n' ...
'sDead=sCurrent; signEps=0.1*problem.currentEpsMargin;\n' ...
'for phase=1:3\n' ...
' if sPrevious(phase)~=sCurrent(phase)\n' ...
'  if iabc(phase)>=signEps, sDead(phase)=0.0;\n' ...
'  elseif iabc(phase)<=-signEps, sDead(phase)=1.0;\n' ...
'  elseif signEps>0.0, sDead(phase)=0.5*(1.0-iabc(phase)/signEps);\n' ...
'  else, sDead(phase)=0.5; end\n' ...
' end\n' ...
'end\n' ...
'sEffective=problem.deadtimeRatio*sDead+(1.0-problem.deadtimeRatio)*sCurrent;\n' ...
'deltaDead=problem.deadtimeRatio*(problem.deltaIabcBase+problem.deltaIabcSwitch*sDead);\n' ...
'deltaStep=problem.deltaIabcBase+problem.deltaIabcSwitch*sEffective;\n' ...
'end\n\n' ...
'function [iabcEnd,lower,upper]=cmv_bounds(iabc,deltaDead,margin)\n' ...
'iabcEnd=iabc+deltaDead; lower=min(iabc,iabcEnd)-margin; upper=max(iabc,iabcEnd)+margin;\n' ...
'end\n']);
end
