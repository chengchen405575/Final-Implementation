function [H, U_unc, iabcCompensated, ...
    deltaIabcBase, deltaIabcSwitch, predictionError, e_dq] = ...
    Assembly_QP_old(Ad, Bd, fd, Gamma, Phi, Apow, ...
    Lambdafsw_Ssquare, Lambdafsw_SE, Bs_TI, ...
    idiq_fb, idiq_ref, Sin_Cos_Theta, theta_el, ...
    wel, Ts, U_applied, ...
    regularization, controllerDelay, ...
    iabcPredictedPrevious, predictionValid, ...
    filterTimeConstant, sensorTimeConstant, phaseShift_rad)
%ASSEMBLY_QP Independent QP-assembly MATLAB Function module.
% Sin_Cos_Theta = [sin(theta_el); cos(theta_el)] at the current instant.
% theta_el is supplied externally at the current instant. Fractional-delay
% compensation uses the current theta/sin/cos values as an approximation;
% no historical angle or additional trigonometric values are calculated.
% U_applied is a fixed 6x1 vector delayed by one SDA period and contains the
% two switching vectors that were physically applied during the measurement
% delay, ordered oldest first:
%   U_applied = [Uapply(k-1); UapplySecond(k-1)].
% The last applied switching state is therefore U_applied(4:6).
% controllerDelay is the external pure delay only (ADC conversion,
% computation, communication and PWM update). The delay caused by the two
% cascaded first-order current filters is supplied by PhaseShift_rad as an
% electrical angle (the PhaseShift LUT must therefore not divide by the
% motor pole-pair count). The time constants are still used to restore the
% fundamental-current magnitude.
%
% The filtered current is treated as an attenuated, delayed estimate of the
% switching-period average current. Its fundamental-frequency magnitude is
% restored, the average current is propagated to the actuation instant, and
% the zero-mean switching ripple produced by the previously applied two
% switching vectors is added afterwards.
% iabcPredictedPrevious is supplied by a model-level Unit Delay block.

Np = 5;
nu = 3;
ny = 2;

% The surrounding FOC model may provide fixed-point fi signals. This QP
% stage uses matrix factorizations and linear solves, so perform all of its
% numerical work consistently in double precision. Mixing a run-time fi
% value with a non-fi matrix in mtimes is not supported by MATLAB Coder.
Ad = double(Ad);
Bd = double(Bd);
fd = double(fd);
Gamma = double(Gamma);
Phi = double(Phi);
Apow = double(Apow);
Lambdafsw_Ssquare = double(Lambdafsw_Ssquare);
Lambdafsw_SE = double(Lambdafsw_SE);
Bs_TI = double(Bs_TI);
idiq_fb = double(idiq_fb);
idiq_ref = double(idiq_ref);
Sin_Cos_Theta = double(Sin_Cos_Theta);
theta_el = double(theta_el); %#ok<NASGU> retained for interface compatibility
wel = double(wel);
Ts = double(Ts);
U_applied = double(U_applied);
regularization = double(regularization);
controllerDelay = double(controllerDelay);
iabcPredictedPrevious = double(iabcPredictedPrevious);
filterTimeConstant = max(0.0,double(filterTimeConstant));
sensorTimeConstant = max(0.0,double(sensorTimeConstant));
phaseShift_rad = double(phaseShift_rad);

sinTheta = Sin_Cos_Theta(1);
cosTheta = Sin_Cos_Theta(2);
Tc = [2/3, -1/3, -1/3; ...
      0, 1/sqrt(3), -1/sqrt(3)];
Rp = [cosTheta, sinTheta; -sinTheta, cosTheta];
TinvClarke = [1.0, 0.0; ...
             -0.5, sqrt(3)/2; ...
             -0.5, -sqrt(3)/2];
Tdq2abc = TinvClarke*Rp.';

uFirst = U_applied(1:3);
uSecond = U_applied(4:6);
uprev = uSecond;
uAverage = 0.5*(uFirst+uSecond);

% Fundamental-frequency response of the cascaded current filters:
%   H(j*w) = 1/((1+j*w*Tf)*(1+j*w*Tsensor)).
% PhaseShift_rad is the signed electrical phase-lag magnitude generated by
% the external LUT:
%   atan(w*Tf) + atan(w*Tsensor).
% Convert it to an equivalent positive time delay. At zero speed,
% atan(w*T)/w tends to T.
omegaTf = wel*filterTimeConstant;
omegaTs = wel*sensorTimeConstant;
omegaThreshold = 1.0e-6;
if abs(wel) > omegaThreshold
    % Accept either a signed atan result or a positive lag magnitude. The
    % equivalent delay used for forward state propagation is always
    % nonnegative.
    filterEquivalentDelay = abs(phaseShift_rad)/abs(wel);
else
    filterEquivalentDelay = filterTimeConstant+sensorTimeConstant;
end
filterEquivalentDelay = max(0.0,filterEquivalentDelay);

% Restore only the fundamental/average-current magnitude. The switching
% ripple is reconstructed from the switching model below; applying this
% inverse gain to the ripple would amplify high-frequency measurement noise.
filterMagnitudeCorrection = ...
    sqrt(1.0+omegaTf*omegaTf)*sqrt(1.0+omegaTs*omegaTs);
iabcAverageDelayed = ...
    filterMagnitudeCorrection*(Tdq2abc*idiq_fb);

% Propagate the delayed average current to the instant at which the newly
% calculated switching command takes effect. U_applied contains only the
% most recent two-vector period, so its average switching state is used as
% the best available average-voltage history. Fixed loop bounds retain
% compatibility with code generation. Eight half-periods cover 8*Ts.
totalCompensationDelay = filterEquivalentDelay+max(0.0,controllerDelay);
iabcAveragePredicted = iabcAverageDelayed;
remainingDelay = min(totalCompensationDelay,8.0*Ts);
for delayStep = 1:8
    if remainingDelay <= 0.0
        break;
    end
    stepFraction = min(1.0,remainingDelay/Ts);
    [deltaBaseAverage,deltaSwitchAverage] = abc_current_increment( ...
        iabcAveragePredicted,Ad,Bd,fd,Bs_TI,wel,Ts, ...
        Tc,Rp,Tdq2abc);
    iabcAveragePredicted = iabcAveragePredicted+stepFraction*( ...
        deltaBaseAverage+deltaSwitchAverage*uAverage);
    remainingDelay = remainingDelay-stepFraction*Ts;
end

% Reconstruct a zero-mean triangular ripple for the equal-duration
% double-vector sequence. At a period boundary the ripple is -DeltaIr1/2;
% at the midpoint it is +DeltaIr1/2. During the external delay the previous
% final vector remains the assumed physically applied state.
[~,deltaSwitchRipple] = abc_current_increment( ...
    iabcAveragePredicted,Ad,Bd,fd,Bs_TI,wel,Ts, ...
    Tc,Rp,Tdq2abc);
deltaRippleFirst = deltaSwitchRipple*(uFirst-uAverage);
iabcRippleEstimated = -0.5*deltaRippleFirst;
externalFraction = min(1.0,max(0.0,controllerDelay/Ts));
iabcRippleEstimated = iabcRippleEstimated+externalFraction*( ...
    deltaSwitchRipple*(uprev-uAverage));

iabcCompensated = iabcAveragePredicted+iabcRippleEstimated;

% Build the optimization and future-prediction model from the reconstructed
% current state at the current electrical angle.
[deltaIabcBase,deltaIabcSwitch,idiqCompensated,Bs] = ...
    abc_current_increment( ...
        iabcCompensated,Ad,Bd,fd,Bs_TI,wel,Ts, ...
        Tc,Rp,Tdq2abc);

Upsil = zeros(ny*Np,nu*Np);
for i = 1:Np
    ri = (i-1)*ny + (1:ny);
    for j = 1:i
        cj = (j-1)*nu + (1:nu);
        Upsil(ri,cj) = ...
            Apow((i-j)*ny + (1:ny),:)*Bs;
    end
end

if predictionValid
    predictionError = iabcCompensated-iabcPredictedPrevious;
else
    predictionError = zeros(3,1);
end
e_dq = Rp*(Tc*predictionError);

r = Gamma*idiqCompensated+Phi-repmat(idiq_ref,Np,1);
W = Upsil.'*Upsil + Lambdafsw_Ssquare;
F = Upsil.'*r-Lambdafsw_SE*uprev;
W = 0.5*(W+W.');
scaleW = max(1,norm(W,'fro'));
n = size(W,1);
W = W+regularization*scaleW*eye(n);

Jx = fliplr(eye(n));
[Rt,p] = chol(Jx*W*Jx);
if p ~= 0
    error('H is not positive definite. Increase lambda_sw or regularization.');
end
H = Jx*Rt*Jx;
y = H.'\(-F);
U_unc = H\y;
end

function [deltaBase,deltaSwitch,idiqState,Bs] = ...
    abc_current_increment( ...
        iabcState,Ad,Bd,fd,Bs_TI,wel,Ts, ...
        Tc,Rp,Tdq2abc)
% One discrete PMSM current step in abc coordinates. The coordinate
% transformations are assembled once by Assembly_QP and passed in.
Jrot = [0 -1; 1 0];

idiqState = Rp*(Tc*iabcState);
Bs = Bd*Rp*Bs_TI;
deltaIdqBase = (Ad-eye(2))*idiqState+fd;
deltaBase = Tdq2abc* ...
    (deltaIdqBase+Jrot*idiqState*(wel*Ts));
deltaSwitch = Tdq2abc*Bs;
end
