    'GotoTag','harness_start','TagVisibility','global','Position',[485 650 600 670]);
add_block('simulink/Signal Routing/Goto',[model '/Goto_CompareEnable'], ...
    'GotoTag','harness_compare_enable','TagVisibility','global','Position',[485 685 600 705]);
