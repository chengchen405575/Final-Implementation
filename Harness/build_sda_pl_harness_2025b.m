function add_annotation(model)
note = sprintf(['Offline transaction replay (100 MHz)\n' ...
    'LOAD -> one-cycle START -> WAIT resultValid -> COMPARE -> NEXT\n' ...
    'Change sdaHarnessCaseLimit in the base workspace for longer runs.\n' ...
    'Summary vector: [lastPass passCount failCount compared maxAbs maxRel mismatchMask]']);
a = Simulink.Annotation(model,note);
a.Position = [620 20 1450 85];
end

function set_chart_script(path,script)
chart = find(sfroot,'-isa','Stateflow.EMChart','Path',path);
assert(~isempty(chart),'SDA:ChartNotFound','Cannot locate MATLAB Function block %s.',path);
chart.Script = script;
end

function text = controller_script()
text = sprintf([ ...
'function [caseIndex,start,compareEnable,done] = fcn(busy,resultValid,fault,caseLimit)\n' ...
'%%#codegen\n' ...
'persistent index state\n' ...
'if isempty(index), index=uint32(1); state=uint8(0); end\n' ...
'caseIndex=index; start=false; compareEnable=false; done=false;\n' ...
'switch state\n' ...
' case 0 %% allow selected problem to settle\n' ...
'  if caseLimit==0, done=true; else, state=uint8(1); end\n' ...
' case 1 %% exactly one 100 MHz start pulse\n' ...
'  start=true; state=uint8(2);\n' ...
' case 2 %% hold inputs while PL searches\n' ...
'  if fault, compareEnable=true; state=uint8(3);\n' ...
'  elseif resultValid, compareEnable=true; state=uint8(3); end\n' ...
' case 3 %% advance only after comparison sampled the old index\n' ...
'  if index>=caseLimit, done=true; state=uint8(4);\n' ...
'  else, index=index+uint32(1); state=uint8(0); end\n' ...
' otherwise\n' ...
'  done=true;\n' ...
'end\n' ...
'end\n']);
end

function text = comparator_script()
text = sprintf([ ...
'function [lastPass,passCount,failCount,comparedCount,maxAbsError,maxRelError,mismatchMask] = fcn(pl,ref,enable,absTol,relTol)\n' ...
'%%#codegen\n' ...
'persistent pCount fCount cCount maxAbs maxRel last mask\n' ...
'if isempty(pCount), pCount=uint32(0); fCount=uint32(0); cCount=uint32(0); maxAbs=0.0; maxRel=0.0; last=true; mask=uint32(0); end\n' ...
'if enable\n' ...
' exactOK = isequal(pl.nodes,ref.nodes) && isequal(pl.optimal,ref.optimal) && ...\n' ...
'  isequal(pl.Uopt,ref.Uopt) && isequal(pl.Uapply,ref.Uapply) && ...\n' ...
'  isequal(pl.predictionValidNext,ref.predictionValidNext) && ...\n' ...
'  isequal(pl.leafNodes,ref.leafNodes) && ...\n' ...
'  isequal(pl.switchCountApplied,ref.switchCountApplied);\n' ...
' a=[pl.Jopt;pl.iabcPredictedNext(:);pl.bestCMVCost;pl.cmvMetricRatio;pl.debug_lower(:);pl.debug_upper(:);pl.Jround;pl.Jshift];\n' ...
' b=[ref.Jopt;ref.iabcPredictedNext(:);ref.bestCMVCost;ref.cmvMetricRatio;ref.debug_lower(:);ref.debug_upper(:);ref.Jround;ref.Jshift];\n' ...
' e=max(abs(a-b)); scale=max(1.0,max(abs(b))); r=e/scale; floatOK=e<=absTol+relTol*scale;\n' ...
' last=exactOK && floatOK; cCount=cCount+uint32(1); maxAbs=max(maxAbs,e); maxRel=max(maxRel,r);\n' ...
' if last, pCount=pCount+uint32(1); else, fCount=fCount+uint32(1); end\n' ...
' mask=uint32(0);\n' ...
' if ~isequal(pl.nodes,ref.nodes), mask=bitor(mask,uint32(1)); end\n' ...
' if ~isequal(pl.leafNodes,ref.leafNodes), mask=bitor(mask,uint32(2)); end\n' ...
' if ~isequal(pl.Uopt,ref.Uopt), mask=bitor(mask,uint32(4)); end\n' ...
' if ~isequal(pl.Uapply,ref.Uapply), mask=bitor(mask,uint32(8)); end\n' ...
' if ~floatOK, mask=bitor(mask,uint32(16)); end\n' ...
'end\n' ...
'lastPass=last; passCount=pCount; failCount=fCount; comparedCount=cCount; maxAbsError=maxAbs; maxRelError=maxRel; mismatchMask=mask;\n' ...
'end\n']);
end

function close_if_loaded(model)
if bdIsLoaded(model), close_system(model,0); end
end
