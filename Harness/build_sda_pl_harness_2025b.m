function build_sda_pl_harness_2025b()
%BUILD_SDA_PL_HARNESS_2025B Complete the existing offline PL test harness.
assert(strcmp(version('-release'),'2025b'),'SDA:WrongRelease', ...
    'Build this harness only with MATLAB R2025b.');
harnessDir = fileparts(mfilename('fullpath'));
rootDir = fileparts(harnessDir);
modelFile = fullfile(harnessDir,'SDA_PL_Harness_2025b.slx');
setup_sda_harness_workspace_2025b;
h = load_system(modelFile);
model = get_param(h,'Name');
cleanup = onCleanup(@() close_if_loaded(model)); %#ok<NASGU>

framework = [model '/SDA_PL_Framework'];
assert(getSimulinkBlockHandle(framework)>0,'SDA:MissingFramework', ...
    'The existing SDA_PL_Framework block was not found.');

backupDir = fullfile(harnessDir,'backups');
if ~isfolder(backupDir), mkdir(backupDir); end
copyfile(modelFile,fullfile(backupDir, ...
    ['SDA_PL_Harness_2025b_before_playback_' datestr(now,'yyyymmdd_HHMMSS') '.slx']));

% Preserve the user-created framework and rebuild only its top-level harness.
top = find_system(model,'SearchDepth',1,'Type','Block');
for k = 1:numel(top)
    if ~strcmp(top{k},framework), delete_block(top{k}); end
end
lines = find_system(model,'SearchDepth',1,'FindAll','on','Type','line');
for k = 1:numel(lines)
    if ishandle(lines(k)), delete_line(lines(k)); end
end
set_param(framework,'Position',[800 105 1010 495]);

set_param(model,'SolverType','Fixed-step','Solver','FixedStepDiscrete', ...
    'FixedStep','1e-8','StopTime','inf','SignalLogging','on', ...
    'SignalLoggingName','logsout');
set_param(model,'DataDictionary','FOC_params.sldd');
set_param(model,'PreLoadFcn',sprintf("addpath('%s');",strrep(harnessDir,"'","''")));
set_param(model,'InitFcn','setup_sda_harness_workspace_2025b;');

add_controller(model);
[inputSources,referenceSources] = add_dataset_selectors(model);
connect_inputs(model,framework,inputSources);
[plBus,referenceBus] = add_result_buses(model,framework,referenceSources);
add_comparator(model,plBus,referenceBus);
add_monitors(model,framework);
add_annotation(model);

save_system(model,modelFile);
set_param(model,'SimulationCommand','update');
save_system(model,modelFile);
fprintf('Completed offline SDA PL harness: %s\n',modelFile);
end

function add_controller(model)
