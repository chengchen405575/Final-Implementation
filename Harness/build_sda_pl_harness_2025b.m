function sources = add_selector_bank(model,prefix,spec,x,y)
sources = cell(size(spec,1),1);
for k=1:size(spec,1)
    name = spec{k,1}; dims = spec{k,2}; expression = spec{k,3};
    c = [model '/' prefix '_Data_' name];
    s = [model '/' prefix '_Select_' name];
    f = [model '/' prefix '_Index_' name];
    add_block('simulink/Sources/Constant',c,'Value',expression, ...
        'Position',[x y+42*(k-1) x+115 y+22+42*(k-1)]);
    add_block('simulink/Signal Routing/From',f,'GotoTag','harness_case_index', ...
        'Position',[x+135 y+27+42*(k-1) x+215 y+47+42*(k-1)]);
    if all(dims==1)
        nDims = 2; options = {'Index vector (dialog)','Index vector (port)'};
    elseif dims(2)==1
        nDims = 2; options = {'Select all','Index vector (port)'};
    else
        nDims = 3; options = {'Select all','Select all','Index vector (port)'};
    end
    add_block('simulink/Signal Routing/Selector',s, ...
        'NumberOfDimensions',num2str(nDims),'IndexMode','One-based', ...
        'IndexOptionArray',options,'IndexParamArray',repmat({'1'},1,nDims), ...
        'Position',[x+245 y+42*(k-1) x+300 y+30+42*(k-1)]);
    add_line(model,[get_param(c,'Name') '/1'],[get_param(s,'Name') '/1'],'autorouting','on');
    add_line(model,[get_param(f,'Name') '/1'],[get_param(s,'Name') '/2'],'autorouting','on');
    sources{k} = [get_param(s,'Name') '/1'];
end
end

function connect_inputs(model,framework,sources)
for k=1:numel(sources)
    add_line(model,sources{k},['SDA_PL_Framework/' num2str(k)],'autorouting','on');
end
add_block('simulink/Signal Routing/From',[model '/From_Start'], ...
    'GotoTag','harness_start','Position',[650 500 745 520]);
add_line(model,'From_Start/1','SDA_PL_Framework/12','autorouting','on');
end

function [plBus,referenceBus] = add_result_buses(model,framework,referenceSources)
plBus = 'PL_Result_Bus/1'; referenceBus = 'Reference_Result_Bus/1';
elementNames = {'Jopt','nodes','optimal','Uopt','Uapply', ...
    'predictionValidNext','iabcPredictedNext','leafNodes','bestCMVCost', ...
    'cmvMetricRatio','switchCountApplied','debug_lower','debug_upper', ...
    'Jround','Jshift','solutionToggle'};
add_block('simulink/Signal Routing/Bus Creator',[model '/PL_Result_Bus'], ...
    'Inputs','16','OutDataTypeStr','Bus: SdaComparisonResultBus', ...
    'Position',[1080 110 1085 450]);
add_block('simulink/Signal Routing/Bus Creator',[model '/Reference_Result_Bus'], ...
    'Inputs','16','OutDataTypeStr','Bus: SdaComparisonResultBus', ...
    'Position',[1430 110 1435 450]);
for k=1:16
    plLine = add_line(model,['SDA_PL_Framework/' num2str(k+1)], ...
        ['PL_Result_Bus/' num2str(k)],'autorouting','on');
    set_param(plLine,'Name',elementNames{k});
    referenceLine = add_line(model,referenceSources{k}, ...
        ['Reference_Result_Bus/' num2str(k)],'autorouting','on');
    set_param(referenceLine,'Name',elementNames{k});
end
end

